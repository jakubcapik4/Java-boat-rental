package pozicovna;

/**
 * Enum reprezentujúci rôzne typy paliva používané v dopravných prostriedkoch požičovne.
 * Každá hodnota označuje špecifický typ paliva, ktorý môže byť použitý v spaľovacích
 * motoroch lodí alebo iných prostriedkov.
 *
 * @author Jakub Capík
 * @version 1.0
 * @since 2025-05-11
 */
public enum Palivo {
    /**
     * Benzín, palivo používané v benzínových motoroch.
     */
    BENZIN,

    /**
     * Nafta, palivo používané v naftových motoroch.
     */
    DIESEL,

    /**
     * Láska-sila, špeciálne palivo (možná metafora alebo špecifické palivo v požičovni).
     */
    L_SILA;
}